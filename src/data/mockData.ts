const getIsoDateOffset = (days: number): string => {
  const d = new Date();
  d.setDate(d.getDate() + days);
  return d.toISOString().split('T')[0];
};

const getRelativeTimeSlot = (offsetMinutes: number, durationMinutes: number = 150): string => {
  const start = new Date(Date.now() + offsetMinutes * 60000);
  let sh = start.getHours();
  const sm = start.getMinutes();
  const sampm = sh >= 12 ? 'PM' : 'AM';
  sh = sh % 12 || 12;

  const end = new Date(start.getTime() + durationMinutes * 60000);
  let eh = end.getHours();
  const em = end.getMinutes();
  const eampm = eh >= 12 ? 'PM' : 'AM';
  eh = eh % 12 || 12;

  return `${String(sh).padStart(2, '0')}:${String(sm).padStart(2, '0')} ${sampm} - ${String(eh).padStart(2, '0')}:${String(em).padStart(2, '0')} ${eampm}`;
};

